#!/usr/bin/env python3
"""Export CASTLE.RAN room records to JSON, plain text, and a Go source file.

Record layout (575 bytes, rooms 1..83, then a high-score record):
  0..431    map, 18 rows x 24 columns, CP437
  432..556  description, 5 lines x 25 columns
  557..574  exits, e.g. "N3S1" (direction letter + room number)
"""
import json
import re
import sys
from pathlib import Path

REC = 575
W, H = 24, 18


def cp437(b: bytes) -> str:
    return b.decode("cp437")


def main(ran: Path, out: Path) -> None:
    data = ran.read_bytes()
    out.mkdir(parents=True, exist_ok=True)
    rooms = []
    for i in range(83):
        r = data[i * REC:(i + 1) * REC]
        rows = [cp437(r[y * W:(y + 1) * W]) for y in range(H)]
        desc_lines = [cp437(r[432 + k * 25:432 + (k + 1) * 25]) for k in range(5)]
        exits_raw = cp437(r[557:575])
        exits = {d: int(n) for d, n in re.findall(r"([NSEWUD])(\d+)", exits_raw)}
        rooms.append({
            "id": i + 1,
            "map": rows,
            "description_lines": desc_lines,
            "description": " ".join(" ".join(desc_lines).split()),
            "exits_raw": exits_raw.rstrip(),
            "exits": exits,
        })
    hs = data[83 * REC:84 * REC]
    high = {"name": cp437(hs[:25]).strip(), "score_field": cp437(hs[25:50]).strip()}

    (out / "rooms.json").write_text(
        json.dumps({"rooms": rooms, "high_score_record": high}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8")

    # Human-readable text dump.
    with open(out / "rooms.txt", "w", encoding="utf-8") as f:
        for rm in rooms:
            f.write(f"=== Room {rm['id']}  exits: {rm['exits_raw']}\n")
            f.write("\n".join(rm["map"]) + "\n")
            f.write("\n".join(l.rstrip() for l in rm["description_lines"]) + "\n\n")

    # Go source with raw-string maps (no backticks occur in the data).
    with open(out / "rooms.go", "w", encoding="utf-8") as f:
        f.write("// Code generated by export_rooms.py from CASTLE.RAN; DO NOT EDIT.\n\n")
        f.write("package castle\n\n")
        f.write("type Room struct {\n\tID          int\n\tMap         string // 18 rows x 24 cols, rows joined by \\n\n"
                "\tDescription [5]string // original 25-column lines\n\tExits       map[byte]int\n}\n\n")
        f.write("var Rooms = [...]Room{\n\t{}, // index 0 unused; rooms are 1-based as in the original\n")
        for rm in rooms:
            ex = ", ".join(f"'{d}': {n}" for d, n in rm["exits"].items())
            desc = ", ".join(json.dumps(l, ensure_ascii=False) for l in rm["description_lines"])
            f.write(f"\t{{ // room {rm['id']}\n\t\tID: {rm['id']},\n\t\tMap: `" + "\n".join(rm["map"]) + "`,\n")
            f.write(f"\t\tDescription: [5]string{{{desc}}},\n\t\tExits: map[byte]int{{{ex}}},\n\t}},\n")
        f.write("}\n")
    print(f"wrote {len(rooms)} rooms to {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
