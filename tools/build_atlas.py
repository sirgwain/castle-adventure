#!/usr/bin/env python3
"""Lay the 83 rooms out as connected maps; write out/atlas.json, atlas.txt and atlas.html.

Rooms joined by N/S/E/W exits form an "area"; areas are joined by U/D stairs and
get a floor number from the stairs (ground floor = 0). Inside an area each room
is a 24x18 cell on a grid. Exits are all two-way, but a few rooms are wider than
one cell, so when a room's natural cell is taken the edge is stretched further
in the same direction; those edges are listed as "stretched".
"""
import json
from collections import deque
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "out"
STEP = {"N": (0, -1), "S": (0, 1), "E": (1, 0), "W": (-1, 0)}
W, H = 24, 18

AREA_NAMES = {
    1: "Ground Floor", 19: "Upper Floor", 34: "Coloured Rooms", 42: "Upper Battlements",
    48: "Castle Walls", 52: "King's Quarters", 62: "West Tower", 63: "East Tower",
    64: "West Tower Top", 65: "East Tower Top", 68: "Cellars and Dungeon",
}


def load():
    rooms = {r["id"]: r for r in json.loads((OUT / "rooms.json").read_text())["rooms"]}
    om = json.loads((OUT / "objects_monsters.json").read_text())
    return rooms, om


def areas(rooms):
    seen, result = set(), []
    for s in sorted(rooms):
        if s in seen:
            continue
        comp, q = {s}, deque([s])
        while q:
            a = q.popleft()
            for d, b in rooms[a]["exits"].items():
                if d in STEP and b not in comp:
                    comp.add(b)
                    q.append(b)
        seen |= comp
        result.append(sorted(comp))
    return result


def layout(rooms, comp, start):
    pos, occ, q, stretched = {start: (0, 0)}, {(0, 0): start}, deque([start]), []
    while q:
        a = q.popleft()
        for d, b in rooms[a]["exits"].items():
            if d not in STEP or b in pos:
                continue
            dx, dy = STEP[d]
            x, y = pos[a][0] + dx, pos[a][1] + dy
            while (x, y) in occ:
                x, y = x + dx, y + dy
            pos[b] = (x, y)
            occ[(x, y)] = b
            q.append(b)
    for a in comp:
        for d, b in rooms[a]["exits"].items():
            if d in STEP and a < b:
                dx, dy = STEP[d]
                if (pos[a][0] + dx, pos[a][1] + dy) != pos[b]:
                    stretched.append((a, d, b))
    xs = [p[0] for p in pos.values()]
    ys = [p[1] for p in pos.values()]
    pos = {r: (x - min(xs), y - min(ys)) for r, (x, y) in pos.items()}
    return pos, stretched, (max(xs) - min(xs) + 1, max(ys) - min(ys) + 1)


def best_layout(rooms, comp):
    best = None
    for s in comp:
        pos, st, (w, h) = layout(rooms, comp, s)
        score = (len(st), w * h)
        if best is None or score < best[0]:
            best = (score, pos, st, (w, h))
    return best[1:]


def floors(rooms, comps):
    area_of = {r: k for k, c in enumerate(comps) for r in c}
    floor = {area_of[1]: 0}
    q = deque([area_of[1]])
    while q:
        a = q.popleft()
        for r in comps[a]:
            for d, b in rooms[r]["exits"].items():
                if d in "UD" and area_of[b] not in floor:
                    floor[area_of[b]] = floor[a] + (1 if d == "U" else -1)
                    q.append(area_of[b])
    return floor, area_of


def main():
    rooms, om = load()
    comps = areas(rooms)
    floor, area_of = floors(rooms, comps)
    data = {"cell": [W, H], "areas": [], "rooms": {}, "objects": om["objects"], "monsters": om["monsters"]}
    text = ["CASTLE ADVENTURE - ATLAS", "Generated by tools/build_atlas.py from CASTLE.RAN.", ""]
    for k, comp in enumerate(comps):
        pos, stretched, (gw, gh) = best_layout(rooms, comp)
        name = AREA_NAMES.get(comp[0], f"Area {comp[0]}")
        stairs = [{"from": r, "dir": d, "to": b, "area": area_of[b]}
                  for r in comp for d, b in rooms[r]["exits"].items() if d in "UD"]
        data["areas"].append({"id": k, "name": name, "floor": floor[k], "size": [gw, gh],
                              "rooms": {str(r): pos[r] for r in comp}, "stairs": stairs,
                              "stretched": stretched})
        # stitched text map
        grid = [[" "] * (gw * W) for _ in range(gh * H)]
        for r, (x, y) in pos.items():
            for row, line in enumerate(rooms[r]["map"]):
                for col, ch in enumerate(line):
                    grid[y * H + row][x * W + col] = ch
            tag = f"[{r}]"   # room number in the first clear corner of its cell
            spots = [(y * H, x * W), (y * H, x * W + W - len(tag)),
                     (y * H + H - 1, x * W), (y * H + H - 1, x * W + W - len(tag))]
            spots += [(y * H + e, x * W + i) for e in (0, H - 1, 1, H - 2) for i in range(W - len(tag) + 1)]
            for gy, gx in spots:
                if all(grid[gy][gx + i] == " " for i in range(len(tag))):
                    grid[gy][gx:gx + len(tag)] = list(tag)
                    break
        text.append("=" * 72)
        text.append(f"{name}  (floor {floor[k]:+d}; rooms {', '.join(map(str, comp))})")
        for s in stairs:
            text.append(f"  stairs: room {s['from']} {'up' if s['dir'] == 'U' else 'down'} to room {s['to']}"
                        f" ({data['areas'][-1]['name'] if s['area'] == k else AREA_NAMES.get(comps[s['area']][0])})")
        for a, d, b in stretched:
            text.append(f"  note: room {a} exit {d} leads to room {b}, which is not drawn adjacent")
        text.append("")
        text += ["".join(row).rstrip() for row in grid]
        text.append("")
    for r in rooms.values():
        data["rooms"][str(r["id"])] = {"map": r["map"], "desc": r["description"], "exits": r["exits"],
                                       "area": area_of[r["id"]]}
    (OUT / "atlas.json").write_text(json.dumps(data, ensure_ascii=False) + "\n", encoding="utf-8")
    (OUT / "atlas.txt").write_text("\n".join(text) + "\n", encoding="utf-8")
    # interactive page: the template with the atlas data inlined
    tpl = (Path(__file__).with_name("atlas_template.html")).read_text(encoding="utf-8")
    page = tpl.replace("__ATLAS__", json.dumps(data, ensure_ascii=False))
    (OUT / "atlas.html").write_text("<!doctype html>\n<meta charset=\"utf-8\">\n"
                                    "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
                                    + page, encoding="utf-8")
    for a in data["areas"]:
        print(f"{a['name']:<22} floor {a['floor']:+d}  grid {a['size'][0]}x{a['size'][1]}  "
              f"rooms {len(a['rooms']):>2}  stretched {a['stretched']}")


if __name__ == "__main__":
    main()
